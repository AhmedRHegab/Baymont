    public static string Get(string? entity, string property)
    {
        var p = Pascal(property);
        if (entity is not null && Labels.TryGetValue($"{entity}.{p}", out var specific)) return specific;
        return Labels.TryGetValue(p, out var label) ? label : p;
    }

    private static string Pascal(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s[1..];
